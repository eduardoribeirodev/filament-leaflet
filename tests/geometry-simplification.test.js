import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import booleanPointInPolygon from '@turf/boolean-point-in-polygon';
import { simplifyFeatureCollections, simplifyGeometryDirectory } from '../scripts/simplify-geometry.mjs';
import { buildLocationIndex, geometryBounds } from '../scripts/build-location-index.mjs';

const collection = (features) => ({ type: 'FeatureCollection', features });
const polygon = (id, coordinates) => ({ type: 'Feature', properties: { shapeID: id, shapeName: `Area ${id}` },
    geometry: { type: 'Polygon', coordinates: [coordinates] } });
const square = (x, y, width) => [[x, y], [x + width, y], [x + width, y + width], [x, y + width], [x, y]];

test('simplification uses one topology for shared borders across separate files', async () => {
    const shared = [[1, 0], [1.00001, 0.0025], [0.99999, 0.005], [1.00001, 0.0075], [1, 0.01]];
    const left = polygon('left', [[0, 0], ...shared, [0, 0.01], [0, 0]]);
    const right = polygon('right', [...shared.toReversed(), [2, 0], [2, 0.01], shared.at(-1)]);
    const originalProperties = structuredClone([left.properties, right.properties]);
    const report = await simplifyFeatureCollections([collection([left]), collection([right])]);
    assert.ok(report.afterVertices < report.beforeVertices);
    const border = (feature) => feature.geometry.coordinates[0].filter(([x]) => x > 0.99 && x < 1.01)
        .filter((point, i, points) => points.findIndex(([x, y]) => x === point[0] && y === point[1]) === i)
        .sort((a, b) => a[1] - b[1]);
    assert.deepEqual(border(left), [[1, 0], [1, 0.01]]);
    assert.deepEqual(border(right), border(left));
    assert.deepEqual([left.properties, right.properties], originalProperties);
});

test('every tiny island and hole survives, preserving feature types and identities', async () => {
    const feature = { ...polygon('islands', square(0, 0, 1)), bbox: [0, 0, 20, 20], geometry: {
        type: 'MultiPolygon', coordinates: [
            [square(0, 0, 1), square(0.4, 0.4, 0.00001).reverse()],
            [square(2, 2, 0.00001)],
        ],
    } };
    const empty = { type: 'Feature', properties: { shapeID: 'empty' }, geometry: null };
    const data = collection([feature, empty]);
    const report = await simplifyFeatureCollections([data]);
    assert.equal(report.rings, 3);
    assert.equal(data.features.length, 2);
    assert.equal(feature.geometry.type, 'MultiPolygon');
    assert.equal(feature.geometry.coordinates.length, 2);
    assert.equal(feature.geometry.coordinates[0].length, 2);
    assert.equal(feature.bbox, undefined, 'Changed bounds must be regenerated by the index builder.');
    assert.equal(feature.properties.shapeID, 'islands');
    assert.equal(empty.geometry, null);
    assert.equal(booleanPointInPolygon([0.400005, 0.400005], feature), false);
    assert.equal(booleanPointInPolygon([2.000005, 2.000005], feature), true);
    for (const ring of feature.geometry.coordinates.flat()) {
        assert.ok(ring.length >= 4);
        assert.deepEqual(ring[0], ring.at(-1));
    }
});

test('date-line polygons keep their longitude range and wrapped bounds', async () => {
    const feature = polygon('date-line', [[179.9, 10], [-179.9, 10], [-179.9, 11], [179.9, 11], [179.9, 10]]);
    await simplifyFeatureCollections([collection([feature])]);
    assert.deepEqual(geometryBounds([feature]), [179.9, 10, -179.9, 11]);
    assert.equal(feature.geometry.type, 'Polygon');
    assert.ok(feature.geometry.coordinates[0].every(([lng]) => lng >= -180 && lng <= 180));
});

test('repeating the same simplification preserves the resulting geometry', async () => {
    const feature = polygon('repeat', [[0, 0], [0.5, 0.00001], [1, 0], [1, 1], [0.5, 1.00001], [0, 1], [0, 0]]);
    const data = collection([feature]);
    await simplifyFeatureCollections([data]);
    const first = structuredClone(data);
    const report = await simplifyFeatureCollections([data]);
    assert.equal(report.skipped, true);
    assert.deepEqual(data, first);
    await assert.rejects(simplifyFeatureCollections([data], 0), /positive/);
    await assert.rejects(simplifyFeatureCollections([data], 50), /fresh source geometry/);
    feature.geometry.coordinates[0][1][0] += 0.00001;
    await assert.rejects(simplifyFeatureCollections([data]), /fresh source geometry/);
});

test('directory rebuilds preserve indexed file bytes and reject mixed source geometry', async () => {
    const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'leaflet-simplification-'));
    try {
        fs.mkdirSync(path.join(directory, 'BRA/MT'), { recursive: true });
        const feature = polygon('test', [[0, 0], [0.5, 0.00001], [1, 0], [1, 1], [0, 1], [0, 0]]);
        feature.properties.shapeISO = 'BR-MT';
        const files = ['BRA/adm0.geojson', 'BRA/adm1.geojson', 'BRA/MT/adm2.geojson'];
        files.forEach((file) => fs.writeFileSync(path.join(directory, file), JSON.stringify(collection([feature]))));
        const first = await simplifyGeometryDirectory(directory);
        assert.equal(first[0].skipped, false);
        buildLocationIndex(directory);
        const indexed = files.map((file) => fs.readFileSync(path.join(directory, file), 'utf8'));
        const repeated = await simplifyGeometryDirectory(directory);
        assert.equal(repeated[0].skipped, true);
        files.forEach((file, index) => assert.equal(fs.readFileSync(path.join(directory, file), 'utf8'), indexed[index]));
        fs.writeFileSync(path.join(directory, files[0]), JSON.stringify(collection([feature])));
        await assert.rejects(simplifyGeometryDirectory(directory), /fresh source geometry/);
    } finally { fs.rmSync(directory, { recursive: true, force: true }); }
});
